"""Monte Carlo simulation: block-bootstrap confidence intervals and forward equity projection.

Two public functions:
  - block_bootstrap_metrics  → 90% CI bands on Sharpe, Max Drawdown, CAGR
  - forward_projection       → P10 / P50 / P90 equity fan for a future horizon

Both use the circular block-bootstrap (Politis & Romano, 1994) with an optimal
block size of sqrt(T) to preserve the autocorrelation structure of daily returns.
GBM / parametric assumptions are deliberately avoided.
"""

from __future__ import annotations

import numpy as np
import pandas as pd


# ── Internal helpers ─────────────────────────────────────────────────────────


def _sharpe(returns: np.ndarray, risk_free_annual: float = 0.0) -> float:
    """Annualised Sharpe ratio for a 1-D daily return array."""
    rf_daily = risk_free_annual / 252.0
    excess = returns - rf_daily
    std = float(np.std(excess, ddof=1))
    if std == 0.0:
        return 0.0
    return float(np.mean(excess) / std * np.sqrt(252.0))


def _max_drawdown(returns: np.ndarray) -> float:
    """Peak-to-trough maximum drawdown (negative float)."""
    equity = np.cumprod(1.0 + returns)
    running_max = np.maximum.accumulate(equity)
    dd = (equity - running_max) / running_max
    return float(dd.min())


def _cagr(returns: np.ndarray) -> float:
    """Compounded annual growth rate over the length of the return array."""
    n = len(returns)
    if n == 0:
        return 0.0
    total = float(np.prod(1.0 + returns))
    years = n / 252.0
    if years <= 0 or total <= 0:
        return 0.0
    return total ** (1.0 / years) - 1.0


def _make_synthetic(
    r_ext: np.ndarray,
    T: int,
    block_size: int,
    rng: np.random.Generator,
) -> np.ndarray:
    """Draw one synthetic return series of length T via circular block bootstrap."""
    n_blocks = int(np.ceil(T / block_size))
    starts = rng.integers(0, T, size=n_blocks)
    blocks = [r_ext[s : s + block_size] for s in starts]
    return np.concatenate(blocks)[:T]


# ── Public dataclasses ────────────────────────────────────────────────────────


class MonteCarloResult:
    """Results from a block-bootstrap simulation on a strategy's daily returns.

    All CI bounds are at the 5th and 95th percentiles (90% confidence interval).
    """

    __slots__ = (
        "n_simulations",
        "block_size",
        "sharpe_ci_low",
        "sharpe_ci_mid",
        "sharpe_ci_high",
        "max_dd_ci_low",
        "max_dd_ci_mid",
        "max_dd_ci_high",
        "cagr_ci_low",
        "cagr_ci_mid",
        "cagr_ci_high",
        "p_positive_sharpe",
        "p_positive_return",
        "sharpe_distribution",
    )

    def __init__(
        self,
        n_simulations: int,
        block_size: int,
        sharpe_ci_low: float,
        sharpe_ci_mid: float,
        sharpe_ci_high: float,
        max_dd_ci_low: float,
        max_dd_ci_mid: float,
        max_dd_ci_high: float,
        cagr_ci_low: float,
        cagr_ci_mid: float,
        cagr_ci_high: float,
        p_positive_sharpe: float,
        p_positive_return: float,
        sharpe_distribution: list[float],
    ) -> None:
        self.n_simulations = n_simulations
        self.block_size = block_size
        self.sharpe_ci_low = sharpe_ci_low
        self.sharpe_ci_mid = sharpe_ci_mid
        self.sharpe_ci_high = sharpe_ci_high
        self.max_dd_ci_low = max_dd_ci_low
        self.max_dd_ci_mid = max_dd_ci_mid
        self.max_dd_ci_high = max_dd_ci_high
        self.cagr_ci_low = cagr_ci_low
        self.cagr_ci_mid = cagr_ci_mid
        self.cagr_ci_high = cagr_ci_high
        self.p_positive_sharpe = p_positive_sharpe
        self.p_positive_return = p_positive_return
        self.sharpe_distribution = sharpe_distribution  # histogram data for frontend

    def to_dict(self) -> dict:
        """Serialise to a JSON-compatible dictionary for the API layer."""
        return {
            "n_simulations": self.n_simulations,
            "block_size": self.block_size,
            "sharpe_ci_low": round(self.sharpe_ci_low, 4),
            "sharpe_ci_mid": round(self.sharpe_ci_mid, 4),
            "sharpe_ci_high": round(self.sharpe_ci_high, 4),
            "max_dd_ci_low": round(self.max_dd_ci_low, 4),
            "max_dd_ci_mid": round(self.max_dd_ci_mid, 4),
            "max_dd_ci_high": round(self.max_dd_ci_high, 4),
            "cagr_ci_low": round(self.cagr_ci_low, 4),
            "cagr_ci_mid": round(self.cagr_ci_mid, 4),
            "cagr_ci_high": round(self.cagr_ci_high, 4),
            "p_positive_sharpe": round(self.p_positive_sharpe, 4),
            "p_positive_return": round(self.p_positive_return, 4),
            "sharpe_distribution": [round(v, 4) for v in self.sharpe_distribution],
        }


class ForwardProjection:
    """Forward equity-curve fan generated by block-bootstrap path simulation.

    P10 / P50 / P90 at each future trading day, anchored to ``last_equity``.
    """

    __slots__ = ("horizon_days", "n_paths", "p10", "p50", "p90", "last_equity")

    def __init__(
        self,
        horizon_days: int,
        n_paths: int,
        p10: list[float],
        p50: list[float],
        p90: list[float],
        last_equity: float,
    ) -> None:
        self.horizon_days = horizon_days
        self.n_paths = n_paths
        self.p10 = p10
        self.p50 = p50
        self.p90 = p90
        self.last_equity = last_equity

    def to_dict(self) -> dict:
        """Serialise to a JSON-compatible dictionary for the API layer."""
        return {
            "horizon_days": self.horizon_days,
            "n_paths": self.n_paths,
            "p10": [round(v, 2) for v in self.p10],
            "p50": [round(v, 2) for v in self.p50],
            "p90": [round(v, 2) for v in self.p90],
            "last_equity": round(self.last_equity, 2),
        }


# ── Public API ────────────────────────────────────────────────────────────────


def block_bootstrap_metrics(
    returns: pd.Series,
    n_simulations: int = 2000,
    block_size: int | None = None,
    random_seed: int | None = 42,
) -> MonteCarloResult:
    """Compute 90% confidence intervals on key metrics via block-bootstrap.

    Uses the circular block-bootstrap (Politis & Romano, 1994) to resample
    contiguous return blocks, preserving the autocorrelation structure that
    IID resampling would destroy (momentum, volatility clustering).

    The optimal block size follows the Politis-Romano rule: ``sqrt(T)`` where T
    is the number of trading days in the return series.

    Args:
        returns:      Daily net returns from a completed backtest.
        n_simulations: Number of synthetic return series to generate.
        block_size:   Block length for bootstrap. Defaults to ``sqrt(T)``.
        random_seed:  Seed for reproducibility.

    Returns:
        MonteCarloResult with 5th / 50th / 95th percentile CI on Sharpe,
        Max Drawdown, and CAGR, plus probability metrics.
    """
    r = returns.dropna().values.astype(float)
    T = len(r)
    if T < 10:
        raise ValueError(f"Need at least 10 return observations; got {T}.")

    bs = block_size if block_size is not None else max(1, int(np.sqrt(T)))

    # Circular extension avoids edge bias: wrap array so every position can
    # anchor a full block of length `bs`.
    r_ext = np.concatenate([r, r[:bs]])

    rng = np.random.default_rng(random_seed)

    sharpes = np.empty(n_simulations)
    max_dds = np.empty(n_simulations)
    cagrs = np.empty(n_simulations)

    for i in range(n_simulations):
        synthetic = _make_synthetic(r_ext, T, bs, rng)
        sharpes[i] = _sharpe(synthetic)
        max_dds[i] = _max_drawdown(synthetic)
        cagrs[i] = _cagr(synthetic)

    def pct(arr: np.ndarray, q: float) -> float:
        return float(np.percentile(arr, q))

    # Sample 80 evenly-spaced points from the Sharpe distribution for the
    # histogram sparkline rendered in the dashboard.
    hist_sample = sharpes[np.linspace(0, n_simulations - 1, 80, dtype=int)].tolist()

    return MonteCarloResult(
        n_simulations=n_simulations,
        block_size=bs,
        sharpe_ci_low=pct(sharpes, 5),
        sharpe_ci_mid=pct(sharpes, 50),
        sharpe_ci_high=pct(sharpes, 95),
        max_dd_ci_low=pct(max_dds, 5),
        max_dd_ci_mid=pct(max_dds, 50),
        max_dd_ci_high=pct(max_dds, 95),
        cagr_ci_low=pct(cagrs, 5),
        cagr_ci_mid=pct(cagrs, 50),
        cagr_ci_high=pct(cagrs, 95),
        p_positive_sharpe=float((sharpes > 0).mean()),
        p_positive_return=float((cagrs > 0).mean()),
        sharpe_distribution=hist_sample,
    )


def forward_projection(
    returns: pd.Series,
    horizon_days: int = 252,
    n_paths: int = 1000,
    last_equity: float = 1.0,
    block_size: int | None = None,
    random_seed: int | None = 42,
) -> ForwardProjection:
    """Simulate a fan of future equity paths via block-bootstrap resampling.

    Generates ``n_paths`` plausible future trajectories by resampling contiguous
    blocks of the strategy's historical daily returns. The paths start at
    ``last_equity`` and span ``horizon_days`` trading days (~1 year by default).

    This is explicitly non-parametric: no GBM, no normality assumption. The
    resampled blocks preserve momentum and volatility-clustering effects.

    Args:
        returns:      Daily net returns from a completed backtest.
        horizon_days: Number of future trading days to project.
        n_paths:      Number of simulated paths.
        last_equity:  Starting equity value (anchors the fan to the historical curve).
        block_size:   Block length for bootstrap. Defaults to ``sqrt(T)``.
        random_seed:  Seed for reproducibility.

    Returns:
        ForwardProjection with P10 / P50 / P90 lists of length ``horizon_days``.
    """
    r = returns.dropna().values.astype(float)
    T = len(r)
    if T < 10:
        raise ValueError(f"Need at least 10 return observations; got {T}.")

    bs = block_size if block_size is not None else max(1, int(np.sqrt(T)))
    r_ext = np.concatenate([r, r[:bs]])

    rng = np.random.default_rng(random_seed)

    # Build all paths as a (n_paths, horizon_days) matrix for vectorised percentile
    path_matrix = np.empty((n_paths, horizon_days), dtype=float)

    for i in range(n_paths):
        synthetic = _make_synthetic(r_ext, horizon_days, bs, rng)
        # Cumulative product of (1 + r) anchored to last_equity
        path_matrix[i] = np.cumprod(1.0 + synthetic) * last_equity

    p10 = np.percentile(path_matrix, 10, axis=0).tolist()
    p50 = np.percentile(path_matrix, 50, axis=0).tolist()
    p90 = np.percentile(path_matrix, 90, axis=0).tolist()

    return ForwardProjection(
        horizon_days=horizon_days,
        n_paths=n_paths,
        p10=p10,
        p50=p50,
        p90=p90,
        last_equity=last_equity,
    )
